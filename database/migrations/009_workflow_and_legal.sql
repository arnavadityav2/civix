-- ---------------------------------------------------------------------------
-- civix.legal_restriction
-- Documents legal restrictions on entities or artifacts.
-- Legal restriction ≠ physical deletion (INV-12).
-- ---------------------------------------------------------------------------
CREATE TABLE civix.legal_restriction (
    restriction_id       UUID                            PRIMARY KEY DEFAULT gen_random_uuid(),
    target_entity_id     UUID                            NULL REFERENCES civix.entity(entity_id),
    target_artifact_id   UUID                            NULL REFERENCES civix.evidence_artifact(artifact_id),
    restriction_type     civix.legal_restriction_type_enum NOT NULL,
    authority            TEXT                            NOT NULL,  -- Court, law, agency
    court_order_reference TEXT                           NULL,
    effective_range      TSTZRANGE                       NOT NULL,  -- When the restriction is in effect
    scope                TEXT                            NOT NULL,  -- What is restricted
    status               TEXT                            NOT NULL DEFAULT 'ACTIVE',
    -- Values: ACTIVE, LIFTED, EXPIRED
    created_by           UUID                            NOT NULL REFERENCES civix.civix_user(user_id),
    lifted_by            UUID                            NULL REFERENCES civix.civix_user(user_id),
    lifted_at            TIMESTAMPTZ                     NULL,

    CONSTRAINT chk_restriction_has_target
        CHECK (target_entity_id IS NOT NULL OR target_artifact_id IS NOT NULL)
);
-- INV-12: Legal restriction does NOT physically delete data.
-- RLS must handle restricted entity/artifact visibility.

-- ---------------------------------------------------------------------------
-- civix.audit_event
-- Append-only audit trail. NEVER UPDATE or DELETE.
-- INV-13 enforced by trigger in migration 010.
-- ---------------------------------------------------------------------------
CREATE TABLE civix.audit_event (
    audit_id         UUID                    PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id          UUID                    NOT NULL REFERENCES civix.civix_user(user_id),
    action           civix.audit_action_enum NOT NULL,
    target_table     TEXT                    NOT NULL,
    target_id        UUID                    NOT NULL,
    case_context_id  UUID                    NULL REFERENCES civix.investigative_case(case_id),
    ip_address       INET                    NULL,
    timestamp        TIMESTAMPTZ             NOT NULL DEFAULT now(),
    metadata         JSONB                   NULL
);
-- INVARIANT (INV-13): Append-only. BEFORE UPDATE OR DELETE trigger raises exception.
-- Trigger defined in migration 010.

-- ---------------------------------------------------------------------------
-- civix.outbox — Transactional Outbox for Neo4j CDC
-- Authority: ADR-008, INV-20
-- This is the ONLY mechanism for Neo4j synchronization.
-- ---------------------------------------------------------------------------
CREATE TABLE civix.outbox (
    id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    entity_id   UUID        NOT NULL,    -- ID of the PostgreSQL row being synced
    action      TEXT        NOT NULL,    -- UPSERT_NODE, UPSERT_EDGE, DEACTIVATE_NODE,
                                         -- DEACTIVATE_EDGE, TOMBSTONE_NODE, TOMBSTONE_EDGE
    entity_type TEXT        NOT NULL,    -- Table name or logical entity type
    payload     JSONB       NOT NULL,    -- Full payload for Neo4j merge
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    consumed_at TIMESTAMPTZ NULL         -- Set by CDC consumer; NULL = pending
);
-- INV-20: No direct Neo4j write is allowed in application code.
-- ONLY the CDC consumer (future Phase 7) reads from this table.

COMMENT ON TABLE civix.outbox IS
    'Transactional outbox for Neo4j CDC. ONLY mechanism for Neo4j sync. No direct Neo4j writes allowed. ADR-008, INV-20.';
