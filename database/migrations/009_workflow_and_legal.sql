-- ---------------------------------------------------------------------------
-- civix.investigative_lead
-- Generated by AI or investigator. AI CANNOT auto-confirm.
-- ---------------------------------------------------------------------------
CREATE TABLE civix.investigative_lead (
    lead_id              UUID                      PRIMARY KEY DEFAULT gen_random_uuid(),
    case_id              UUID                      NOT NULL REFERENCES civix.investigative_case(case_id),
    generated_by_run_id  UUID                      NULL REFERENCES civix.analysis_run(run_id),
    generated_by_person  UUID                      NULL REFERENCES civix.civix_user(user_id),
    lead_text            TEXT                      NOT NULL,
    explanation          TEXT                      NULL,
    priority             civix.lead_priority_enum  NOT NULL DEFAULT 'MEDIUM',
    status               civix.lead_status_enum    NOT NULL DEFAULT 'OPEN',
    ai_confidence        DECIMAL(5,4)              NULL CHECK (ai_confidence BETWEEN 0.0 AND 1.0),
    created_at           TIMESTAMPTZ               NOT NULL DEFAULT now(),
    disposition_notes    TEXT                      NULL,
    disposed_by          UUID                      NULL REFERENCES civix.civix_user(user_id),
    disposed_at          TIMESTAMPTZ               NULL,

    CONSTRAINT chk_lead_has_origin
        CHECK (generated_by_run_id IS NOT NULL OR generated_by_person IS NOT NULL)
);

-- ---------------------------------------------------------------------------
-- civix.investigation_task
-- Action item derived from a lead or created directly on a case.
-- ---------------------------------------------------------------------------
CREATE TABLE civix.investigation_task (
    task_id        UUID                     PRIMARY KEY DEFAULT gen_random_uuid(),
    lead_id        UUID                     NULL REFERENCES civix.investigative_lead(lead_id),
    case_id        UUID                     NOT NULL REFERENCES civix.investigative_case(case_id),
    task_type      civix.task_type_enum     NOT NULL,
    assigned_to    UUID                     NULL REFERENCES civix.civix_user(user_id),
    status         civix.task_status_enum   NOT NULL DEFAULT 'PENDING',
    due_date       DATE                     NULL,
    outcome_notes  TEXT                     NULL,
    created_at     TIMESTAMPTZ              NOT NULL DEFAULT now(),
    completed_at   TIMESTAMPTZ              NULL

    -- task_status = 'COMPLETED' should correlate with completed_at IS NOT NULL
    -- Enforced at application layer
);

