"""
Synthetic-to-Real Gap analysis — documents limitations of training on Profile C
and what must be validated before deploying against real-world data.
"""

REPORT = """# CIVIX Phase 3A — Synthetic-to-Real Gap Report

> This report is MANDATORY per the Phase 3A spec.
> A model performing well on Profile C does NOT mean it is real-world ready.

## 1. What Profile C Actually Is

Profile C is a synthetic behavioral dataset generated by the CIVIX Synthetic World Engine.
It simulates 250,000 persons in a controlled scenario catalog of 69 crime/behavior patterns.

**It is NOT derived from real Indian law enforcement data.**

---

## 2. Known Synthetic Assumptions

### 2.1 Perfect Scenario Assignment
In Profile C, every person has exactly one assigned `scenario_class`. In reality:
- A person may exhibit behaviors from multiple overlapping patterns.
- Scenario boundaries are fuzzy and investigator-dependent.
- Real criminals adapt to avoid pattern detection.

### 2.2 Artificial Label Clarity
Ground truth in Profile C is a Boolean `is_positive_label`. In reality:
- Labels are derived from investigation outcomes, not ground truth.
- Conviction rates vary by jurisdiction.
- Many genuine criminals are never charged.
- Innocent persons are sometimes charged.

### 2.3 Synthetic Call Volume Distributions
The call volumes were generated from parametric distributions. In reality:
- Call volumes depend on carrier, region, occupation, culture.
- Seasonal patterns (festivals, elections) create spikes.
- Device changes, SIM swapping, and network outages create gaps.

### 2.4 Idealized Geographic Patterns
Geographic features in Profile C use synthetic cell-sector coordinates.
- Real India has 1M+ cell towers vs 8,000 in Profile C.
- Urban vs rural call density differences are not modeled.
- Network handover artifacts are absent.

### 2.5 No Reporting Bias
In Profile C, all suspicious persons have CDRs and transaction records.
In reality:
- High-value criminals may use encrypted channels (WhatsApp, Signal).
- Some criminals use cash exclusively (no transaction trail).
- Missing data is informative — but Profile C has systematic missingness, not realistic gaps.

### 2.6 No Investigation Bias
Profile C labels are generated independently of investigative history.
In reality:
- Persons already under investigation receive more scrutiny → more CDRs logged.
- This creates a feedback loop that inflates features for known suspects.

### 2.7 Temporal Compression
Profile C spans 3 years (2022–2024). Criminal behavioral evolution over years,
regime changes, and legal reforms are not modeled.

---

## 3. Expected Domain Shift

| Feature Category | Synthetic Profile | Expected Reality |
|------------------|-------------------|-----------------|
| Call volume | Parametric (Poisson) | Carrier-dependent, seasonal |
| Transaction amounts | Log-normal, scenario-scaled | Occupation, region, and inflation-dependent |
| Geographic spread | Uniform regional grid | Highly skewed urban/rural |
| Night calls | Bernoulli-rate per scenario | Cultural and occupational variation |
| Scenario boundaries | Crisp | Fuzzy, overlapping |
| Labels | Deterministic | Probabilistic, biased |
| Missing data | Systematic (no CDR = no activity) | Informative (may mean encrypted comms) |

---

## 4. What a Good Performance on Profile C DOES Prove

- The feature engineering is mathematically sound.
- The features do not leak labels.
- The temporal splitting is correctly implemented.
- The model can learn behavioral signals from CDR + transaction aggregates.
- The ranking mechanism produces meaningful relative scores.
- The hard-negative discrimination logic works on synthetic adversarial patterns.
- The inference pipeline is computationally feasible on the target hardware.

## 5. What It Does NOT Prove

- The model will generalize to real Indian law enforcement data.
- The specific thresholds learned are valid outside the synthetic distribution.
- The feature importances will rank the same way on real data.
- The model's precision/recall will match on real data.

---

## 6. Required Steps Before Real-World Deployment

1. **Pilot with anonymized real CDR data** — even 10,000 real records would validate whether the feature distributions match.
2. **Re-calibrate probability thresholds** — Platt scaling parameters will shift on real data.
3. **Validate label quality** — Work with officers to define and validate ground-truth labels from real case outcomes.
4. **Adversarial red-team** — Have investigators try to game the model manually.
5. **Fairness audit** — Check for demographic bias (gender, region, occupation) on real data.
6. **Regulatory review** — Ensure predictions do not constitute automated profiling under applicable law.

---

## 7. Conclusion

> Phase 3A establishes that the CIVIX ML pipeline is **technically operational**.
> It DOES NOT establish real-world effectiveness.
> Do not present synthetic metrics to stakeholders as real-world validation.
"""

